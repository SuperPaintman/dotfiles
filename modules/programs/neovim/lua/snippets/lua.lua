-- See: https://github.com/L3MON4D3/LuaSnip/blob/master/DOC.md
--------------------------------------------------------------------------------
-- Init
--------------------------------------------------------------------------------
local M = {}

--------------------------------------------------------------------------------
-- Modules
--------------------------------------------------------------------------------
M.setup = function()
  local ls = require("luasnip")
  local fmta = require("luasnip.extras.fmt").fmta

  local s = ls.snippet
  local i = ls.insert_node

  ls.add_snippets("lua", {
    -- Neovim.
    s(
      "!header",
      fmta(
        [[
          --------------------------------------------------------------------------------
          -- <header>
          --------------------------------------------------------------------------------
          <>
        ]],
        {
          header = i(1, "Header"),
          i(2),
        }
      )
    ),

    s(
      "!config",
      fmta(
        [[
          --------------------------------------------------------------------------------
          -- Init
          --------------------------------------------------------------------------------
          local M = {}

          --------------------------------------------------------------------------------
          -- Modules
          --------------------------------------------------------------------------------
          M.config = function()
            require("<name>").setup({
              <>
            })
          end

          --------------------------------------------------------------------------------
          -- Export
          --------------------------------------------------------------------------------
          return M
        ]],
        {
          name = i(1, "name"),
          i(2),
        }
      )
    ),
  })
end

--------------------------------------------------------------------------------
-- Export
--------------------------------------------------------------------------------
return M
