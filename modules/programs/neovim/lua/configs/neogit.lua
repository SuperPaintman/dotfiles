--------------------------------------------------------------------------------
-- Init
--------------------------------------------------------------------------------
local M = {
  _initialized = false,
}

local cb = require("utils.mappings").create_callback_factory(
  M,
  "neogit is not initialized"
)

--------------------------------------------------------------------------------
-- Modules
--------------------------------------------------------------------------------
M.config = function()
  require("neogit").setup({})
  M._initialized = true
end

M.mappings = {
  open = cb(function()
    require("neogit").open()
  end),
}

--------------------------------------------------------------------------------
-- Export
--------------------------------------------------------------------------------
return M
