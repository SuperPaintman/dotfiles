--------------------------------------------------------------------------------
-- Init
--------------------------------------------------------------------------------
local M = {}

--------------------------------------------------------------------------------
-- Modules
--------------------------------------------------------------------------------
M.config = function()
  local mappings = require("mappings")

  if
    mappings.telescope ~= nil
    and type(mappings.telescope.config) == "function"
  then
    mappings.telescope.config()
  end
end

--------------------------------------------------------------------------------
-- Export
--------------------------------------------------------------------------------
return M
