--------------------------------------------------------------------------------
-- Imports
--------------------------------------------------------------------------------
local ui = require("core.ui")

--------------------------------------------------------------------------------
-- Init
--------------------------------------------------------------------------------
local M = {}

--------------------------------------------------------------------------------
-- Modules
--------------------------------------------------------------------------------
M.event = "VeryLazy"

M.config = function()
  require("lsp_signature").setup({
    hint_enable = false,
    doc_lines = 0,
    handler_opts = {
      border = ui.borders.thick(),
    },
  })
end

M.reload = function()
  local unload = require("utils.modules").unload
  unload("core.ui")
  M.config()
end

--------------------------------------------------------------------------------
-- Export
--------------------------------------------------------------------------------
return M
